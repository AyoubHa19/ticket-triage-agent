/**
 * Builds the browser demo into _site/ with no dependencies:
 *  - copies site/ (HTML, CSS, the demo's own JS),
 *  - strips the types from the three projects' core modules so the browser runs the same code the tests run,
 *  - bundles the sample data (knowledge base, eval queries, labelled tickets) into data.js.
 *
 * Usage: node scripts/build-site.ts
 */
import { cpSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { stripTypeScriptTypes } from "node:module";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const out = join(root, "_site");
const PROJECTS = ["inbox-agent", "llm-evals", "kb-search"];
/** Entry points and loaders that use Node APIs; the browser demo does not need them. */
const NODE_ONLY = new Set(["load.ts", "run-eval.ts", "demo.ts", "ai-sdk-adapter.ts"]);

rmSync(out, { recursive: true, force: true });
cpSync(join(root, "site"), out, { recursive: true });

let modules = 0;
for (const project of PROJECTS) {
  const srcDir = join(root, project, "src");
  const outDir = join(out, "lib", project, "src");
  mkdirSync(outDir, { recursive: true });

  for (const file of readdirSync(srcDir)) {
    if (!file.endsWith(".ts") || file.endsWith(".test.ts") || NODE_ONLY.has(file)) continue;
    const code = stripTypeScriptTypes(readFileSync(join(srcDir, file), "utf8"), { mode: "strip" })
      .replace(/(from\s+["'])(\.{1,2}\/[^"']+)\.ts(["'])/g, "$1$2.js$3");
    if (/from\s+["']node:/.test(code)) throw new Error(`${project}/src/${file} imports a Node module`);
    writeFileSync(join(outDir, file.replace(/\.ts$/, ".js")), code);
    modules++;
  }
}

const docsDir = join(root, "kb-search", "docs");
const docs = readdirSync(docsDir)
  .filter((f) => f.endsWith(".md"))
  .sort()
  .map((f) => ({ id: f.replace(/\.md$/, ""), markdown: readFileSync(join(docsDir, f), "utf8") }));
const queries = JSON.parse(readFileSync(join(root, "kb-search", "data", "queries.json"), "utf8"));
const tickets = readFileSync(join(root, "llm-evals", "data", "tickets.jsonl"), "utf8");

writeFileSync(
  join(out, "data.js"),
  [
    "// Generated by scripts/build-site.ts from the projects' sample data. Do not edit.",
    `export const docs = ${JSON.stringify(docs)};`,
    `export const queries = ${JSON.stringify(queries)};`,
    `export const ticketsJsonl = ${JSON.stringify(tickets)};`,
    "",
  ].join("\n"),
);

console.log(`Built _site/: ${modules} modules, ${docs.length} documents, ${queries.length} queries.`);
